export type TeamStrings = Strings;

const ALL: Record<RouteLocale, Strings> = { es, pt, en };

export function teamStrings(locale: RouteLocale): Strings {
  return ALL[locale] ?? es;
}

export function asLocale(v: string): RouteLocale {
  return v === 'pt' || v === 'en' ? v : 'es';
}

// "o Brasileirão", "o Championship"; every other competition we cover is
// feminine in Portuguese (a Liga MX, a Premier League, a MLS, a Copa…).
function ptMasculine(name: string): boolean {
  return /^(brasileir|campeonato|torneio|championship)/i.test(name.trim());
}

/** `fill` from lib/site plus the Portuguese contractions of the competition
 *  name ({noL} {doL} {NoL} for {league}, {pelaC} for {competition}). The
 *  es/en templates never use those keys. */
export function fill(template: string, values: Record<string, string>): string {
  const m = ptMasculine(values.league ?? '');
  const c = ptMasculine(values.competition ?? '');
  return baseFill(template, {
    noL: m ? 'no' : 'na',
    NoL: m ? 'No' : 'Na',
    doL: m ? 'do' : 'da',
    pelaC: c ? 'pelo' : 'pela',
    ...values,
  });
}
